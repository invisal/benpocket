/** Expanding, fading ring for the click-ripple effect -- see resolveClickRipple in cursor-path.ts. Drawn stroked-only (not filled) so it reads as a ring emanating outward, not a solid dot. */
function drawClickRippleInto(
  g: Graphics,
  x: number,
  y: number,
  radiusPx: number,
  color: string,
  alpha: number
): void {
  if (radiusPx <= 0 || alpha <= 0) return;
  g.circle(x, y, radiusPx).stroke({ color, width: Math.max(1.5, radiusPx * 0.08), alpha });
}

/**
 * Transforms a glyph-space point (in the shared 24x24 box) into screen-space
 * around `(x, y)`, anchored on `hotspot` rather than the box's own (0,0)
 * corner -- shared by both the plain-glyph and custom-icon draw paths below.
 * `rotationDeg` (only ever non-zero for the resize glyph -- see
 * `ResizeRotationDeg`) spins the point around that same hotspot before
 * translating into place, so the icon rotates in-place at the cursor
 * position rather than swinging around some other origin. Rotation and the
 * (uniform) click-bounce scale commute around a shared origin, so it doesn't
 * matter that rotation is applied before scale here.
 */
function toScreenPoint(
  [px, py]: [number, number],
  hotspot: { x: number; y: number },
  x: number,
  y: number,
  s: number,
  clickScale: number,
  rotationDeg = 0
): [number, number] {
  let lx = px - hotspot.x;
  let ly = py - hotspot.y;
  if (rotationDeg !== 0) {
    const rad = (rotationDeg * Math.PI) / 180;
    const cos = Math.cos(rad);
    const sin = Math.sin(rad);
    const rx = lx * cos - ly * sin;
    const ry = lx * sin + ly * cos;
    lx = rx;
    ly = ry;
  }
  return [x + lx * clickScale * s, y + ly * clickScale * s];
}

function drawCursorIconInto(
  g: Graphics,
  x: number,
  y: number,
  sizePx: number,
  fill: string,
  stroke: string,
  alpha: number,
  clickScale: number,
  gesture: CursorGesture,
  customIcon: CursorCustomIconId | undefined,
  resizeRotationDeg: number
): void {
  const s = sizePx / 24;

  if (gesture === 'idle' && customIcon) {
    // Fully custom illustration -- each subpath keeps its own embedded fill
    // (not the shared `fill`/`stroke` params, which every other glyph
    // takes), so it's filled right after its own moveTo/lineTo/closePath
    // instead of once at the end like the plain-glyph path below.
    const hotspot = CURSOR_CUSTOM_ICON_HOTSPOTS[customIcon];
    for (const { points, fill: pathFill } of CUSTOM_CURSOR_GLYPHS[customIcon]) {
      const pts = points.map((p) => toScreenPoint(p, hotspot, x, y, s, clickScale));
      g.moveTo(pts[0][0], pts[0][1]);
      for (let i = 1; i < pts.length; i++) g.lineTo(pts[i][0], pts[i][1]);
      g.closePath();
      g.fill({ color: pathFill, alpha });
    }
    return;
  }

  if (gesture === 'hover') {
    // Fixed white/black artwork -- not recolored via `fill`/`stroke`
    // (unlike the arrow below), matching CursorStyleIcon.tsx's hover
    // branch exactly so the export stays pixel-identical to the live
    // preview regardless of which cursor color preset is active.
    const hotspot = CURSOR_GESTURE_HOTSPOTS.hover;
    const strokeWidth = CURSOR_HOVER_STROKE_WIDTH * s;
    for (const subPath of CURSOR_HOVER_GLYPH.fill) {
      const pts = subPath.map((p) => toScreenPoint(p, hotspot, x, y, s, clickScale));
      g.moveTo(pts[0][0], pts[0][1]);
      for (let i = 1; i < pts.length; i++) g.lineTo(pts[i][0], pts[i][1]);
      g.closePath();
    }
    g.fill({ color: '#ffffff', alpha });
    // Re-stroke the same contour(s) for the hand's black outline, then the
    // three finger-crease lines on top -- both fixed black, same as the
    // source art.
    for (const subPath of CURSOR_HOVER_GLYPH.fill) {
      const pts = subPath.map((p) => toScreenPoint(p, hotspot, x, y, s, clickScale));
      g.moveTo(pts[0][0], pts[0][1]);
      for (let i = 1; i < pts.length; i++) g.lineTo(pts[i][0], pts[i][1]);
      g.closePath();
      g.stroke({ color: '#000000', width: strokeWidth, alpha });
    }
    for (const [start, end] of CURSOR_HOVER_GLYPH.lines) {
      const [sx, sy] = toScreenPoint(start, hotspot, x, y, s, clickScale);
      const [ex, ey] = toScreenPoint(end, hotspot, x, y, s, clickScale);
      g.moveTo(sx, sy);
      g.lineTo(ex, ey);
      g.stroke({ color: '#000000', width: strokeWidth, alpha });
    }
    return;
  }

  if (gesture === 'resize') {
    // Fixed white/black artwork, same convention as `hover` above (not
    // recolored via `fill`/`stroke`, unlike the plain arrow below) -- the
    // source art is itself a thin outline shape (see CURSOR_RESIZE_GLYPH's
    // own doc on its nonzero-winding hole), so recoloring it via the active
    // cursor style's own colors (often a dark fill meant for a solid arrow)
    // read as barely-visible/transparent against a similarly dark recording.
    const hotspot = CURSOR_GESTURE_HOTSPOTS.resize;
    for (const subPath of CURSOR_RESIZE_GLYPH) {
      const pts = subPath.map((p) =>
        toScreenPoint(p, hotspot, x, y, s, clickScale, resizeRotationDeg)
      );
      g.moveTo(pts[0][0], pts[0][1]);
      for (let i = 1; i < pts.length; i++) g.lineTo(pts[i][0], pts[i][1]);
      g.closePath();
    }
    g.fill({ color: '#ffffff', alpha });
    g.stroke({ color: '#000000', width: s, alpha });
    return;
  }

  if (gesture === 'crosshair') {
    // Fixed white/black artwork, same convention as hover/resize above --
    // a white halo stroke under the black line keeps it readable against
    // any background, matching CursorStyleIcon.tsx's crosshair branch
    // exactly. Stroked only (no fill) -- these are lines, not a silhouette.
    const hotspot = CURSOR_GESTURE_HOTSPOTS.crosshair;
    for (const [start, end] of CURSOR_CROSSHAIR_LINES) {
      const [sx, sy] = toScreenPoint(start, hotspot, x, y, s, clickScale);
      const [ex, ey] = toScreenPoint(end, hotspot, x, y, s, clickScale);
      g.moveTo(sx, sy);
      g.lineTo(ex, ey);
      g.stroke({ color: '#ffffff', width: 3 * s, alpha, cap: 'round' });
    }
    for (const [start, end] of CURSOR_CROSSHAIR_LINES) {
      const [sx, sy] = toScreenPoint(start, hotspot, x, y, s, clickScale);
      const [ex, ey] = toScreenPoint(end, hotspot, x, y, s, clickScale);
      g.moveTo(sx, sy);
      g.lineTo(ex, ey);
      g.stroke({ color: '#000000', width: 1.4 * s, alpha, cap: 'round' });
    }
    return;
  }

  if (gesture === 'textSelect') {
    // Fixed white/black artwork, same convention as crosshair above -- a
    // white halo stroke under the black line keeps it readable against any
    // background, matching CursorStyleIcon.tsx's textSelect branch exactly.
    const hotspot = CURSOR_GESTURE_HOTSPOTS.textSelect;
    for (const [start, end] of CURSOR_TEXT_SELECT_LINES) {
      const [sx, sy] = toScreenPoint(start, hotspot, x, y, s, clickScale);
      const [ex, ey] = toScreenPoint(end, hotspot, x, y, s, clickScale);
      g.moveTo(sx, sy);
      g.lineTo(ex, ey);
      g.stroke({ color: '#ffffff', width: 3 * s, alpha, cap: 'round' });
    }
    for (const [start, end] of CURSOR_TEXT_SELECT_LINES) {
      const [sx, sy] = toScreenPoint(start, hotspot, x, y, s, clickScale);
      const [ex, ey] = toScreenPoint(end, hotspot, x, y, s, clickScale);
      g.moveTo(sx, sy);
      g.lineTo(ex, ey);
      g.stroke({ color: '#000000', width: 1.4 * s, alpha, cap: 'round' });
    }
    return;
  }

  // Only the plain arrow reaches here (idle, no customIcon).
  const hotspot = CURSOR_GESTURE_HOTSPOTS.idle;
  // Anchored so the glyph's own hotspot (not the path's local (0,0) corner)
  // lands exactly on (x, y) -- the actual recorded cursor/click position --
  // rather than offsetting the whole icon down-right by hotspot*s.
  for (const subPath of CURSOR_IDLE_GLYPH) {
    const pts = subPath.map((p) => toScreenPoint(p, hotspot, x, y, s, clickScale));
    g.moveTo(pts[0][0], pts[0][1]);
    for (let i = 1; i < pts.length; i++) g.lineTo(pts[i][0], pts[i][1]);
    g.closePath();
  }
  g.fill({ color: fill, alpha });
  g.stroke({ color: stroke, width: 1.4 * s, alpha });
}

/** Recorded cursor + motion-blur ghost trail + click-bounce, redrawn into one `Graphics` per frame. */
export class CursorEffect {
  private readonly graphics = new Graphics();
  private readonly maskGraphics = new Graphics();
  private readonly container = new Container();

  constructor(parent: Container) {
    // See shadow-corner.ts's constructor comment: `includeInBuild = false`,
    // not `renderable = false` -- the latter also breaks the mask itself.
    this.maskGraphics.includeInBuild = false;
    this.container.addChild(this.maskGraphics, this.graphics);
    parent.addChild(this.container);
  }

  update(cursor: CursorSceneData | null, innerRect: InnerRect): void {
    this.graphics.clear();
    if (!cursor) {
      this.container.visible = false;
      return;
    }
    this.container.visible = true;

    if (cursor.clipToCanvas) {
      this.maskGraphics.clear();
      this.maskGraphics
        .rect(innerRect.x, innerRect.y, innerRect.width, innerRect.height)
        .fill(0xffffff);
      this.container.mask = this.maskGraphics;
    } else {
      this.container.mask = null;
    }

    if (cursor.ripple) {
      drawClickRippleInto(
        this.graphics,
        cursor.ripple.posPx.x,
        cursor.ripple.posPx.y,
        cursor.ripple.radiusPx,
        cursor.fill,
        cursor.ripple.alpha
      );
    }

    for (const ghost of cursor.ghosts) {
      drawCursorIconInto(
        this.graphics,
        ghost.posPx.x,
        ghost.posPx.y,
        cursor.sizePx,
        cursor.fill,
        cursor.stroke,
        ghost.alpha,
        1,
        cursor.gesture,
        cursor.customIcon,
        cursor.resizeRotationDeg
      );
    }
    drawCursorIconInto(
      this.graphics,
      cursor.posPx.x,
      cursor.posPx.y,
      cursor.sizePx,
      cursor.fill,
      cursor.stroke,
      1,
      cursor.clickScale,
      cursor.gesture,
      cursor.customIcon,
      cursor.resizeRotationDeg
    );
  }
}
